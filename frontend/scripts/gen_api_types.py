"""Generate ``frontend/src/api/schema.gen.ts`` from the FastAPI OpenAPI document (D28, D61).

The OpenAPI schema served at ``/api/openapi.json`` is the single contract source. This script
renders its component schemas as TypeScript interfaces with no extra dependency (the
``openapi-typescript`` package named in D28 is not installed; adding it needs approval).

    .venv/bin/python frontend/scripts/gen_api_types.py           # rewrite the file
    .venv/bin/python frontend/scripts/gen_api_types.py --check   # exit 1 if stale

``make api-types`` runs the first form; a backend test runs the second, so a stale file
fails ``make check``.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

OUT = Path(__file__).resolve().parents[1] / "src" / "api" / "schema.gen.ts"
HEADER = (
    "// GENERATED by frontend/scripts/gen_api_types.py from the backend OpenAPI schema.\n"
    "// Do not edit by hand: run `make api-types`. A backend test fails when this is stale.\n"
)


def _ts(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return str(schema["$ref"]).rsplit("/", 1)[-1]
    if "anyOf" in schema:
        parts: list[str] = []
        for sub in schema["anyOf"]:
            t = _ts(sub)
            if t not in parts:
                parts.append(t)
        return " | ".join(parts)
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"])
    kind = schema.get("type")
    if kind == "array":
        inner = _ts(schema.get("items", {}))
        return f"({inner})[]" if " " in inner else f"{inner}[]"
    if kind == "string":
        return "string"
    if kind in ("integer", "number"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    if kind == "object":
        extra = schema.get("additionalProperties")
        if isinstance(extra, dict) and extra:
            return f"Record<string, {_ts(extra)}>"
        return "Record<string, unknown>"
    return "unknown"


def _key(name: str) -> str:
    return name if name.isidentifier() else json.dumps(name)


def render(openapi: dict[str, Any]) -> str:
    out = [HEADER]
    schemas: dict[str, Any] = openapi.get("components", {}).get("schemas", {})
    for name in sorted(schemas):
        schema = schemas[name]
        doc = schema.get("description")
        if doc:
            first = str(doc).strip().splitlines()[0].replace("*/", "*\\/")
            out.append(f"\n/** {first} */")
        else:
            out.append("")
        props = schema.get("properties")
        if props is None:
            out.append(f"export type {name} = {_ts(schema)};")
            continue
        required = set(schema.get("required", []))
        out.append(f"export interface {name} {{")
        for prop, sub in props.items():
            opt = "" if prop in required else "?"
            out.append(f"  {_key(prop)}{opt}: {_ts(sub)};")
        out.append("}")
    return "\n".join(out) + "\n"


def main(argv: list[str]) -> int:
    from erp_backend.main import create_app

    text = render(create_app().openapi())
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.name} is stale: run `make api-types`", file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(Path.cwd()) if OUT.is_relative_to(Path.cwd()) else OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
